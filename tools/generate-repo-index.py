def git(*args: str, cwd: Path = ROOT, env_extra: dict | None = None) -> str:
    import os

    env = dict(os.environ)
    if env_extra:
        env.update(env_extra)
    out = subprocess.run(
        ["git", *args], cwd=cwd, env=env, check=True, capture_output=True
    ).stdout
    return out.decode("utf-8", "surrogateescape")


def list_files() -> list[str]:
    """Tracked + untracked-but-not-ignored files, repo-relative, POSIX separators."""
    inside = subprocess.run(
        ["git", "rev-parse", "--is-inside-work-tree"],
        cwd=ROOT, capture_output=True,
    )
    if inside.returncode == 0 and (ROOT / ".git").exists():
        out = git("ls-files", "-z", "--cached", "--others", "--exclude-standard")
    else:
        with tempfile.TemporaryDirectory() as tmp:
            git("init", "--bare", "-q", tmp)
            out = git(
                f"--git-dir={tmp}", f"--work-tree={ROOT}",
                "ls-files", "-z", "--others", "--exclude-standard",
            )
    names = {n for n in out.split("\0") if n}
    return sorted(
        n for n in names
        if (ROOT / n).is_file() and n not in SELF_OUTPUTS and not n.startswith(".git/")
    )


def read_version() -> str:
    pom = ROOT / "src/java/pom.xml"
    if pom.exists():
        m = re.search(r"<revision>([^<]+)</revision>", pom.read_text(encoding="utf-8"))
        if m:
            return m.group(1).strip()
    return "unknown"


LANG_BY_EXT = {
    ".cs": "C#", ".csproj": "MSBuild", ".java": "Java", ".py": "Python", ".ts": "TypeScript",
    ".js": "JavaScript", ".rs": "Rust", ".md": "Markdown", ".json": "JSON", ".yml": "YAML",
    ".yaml": "YAML", ".sql": "SQL", ".html": "HTML", ".svg": "SVG", ".sh": "Shell",
    ".ps1": "PowerShell", ".xml": "XML", ".csv": "CSV", ".puml": "PlantUML",
}


def build(files: list[str]) -> tuple[dict, str]:
    sizes = {f: (ROOT / f).stat().st_size for f in files}
    version = read_version()

    by_lang: dict[str, int] = defaultdict(int)
    for f in files:
        by_lang[LANG_BY_EXT.get(Path(f).suffix.lower(), "Other")] += 1

    index = {
        "schema": "https://github.com/Foundgine/Foundgine/blob/main/docs/AI-ACCESS.md#repo-indexjson",
        "name": "Foundgine",
        "description": "Configurable semantic and execution boundary for application capabilities (.NET 10 and Java 27).",
        "version": version,
        "license": "Apache-2.0",
        "repository": GITHUB,
        "defaultBranch": BRANCH,
        "website": SITE,
        "access": {
            "clone": f"{GITHUB}.git",
            "zip": f"{GITHUB}/archive/refs/heads/{BRANCH}.zip",
            "tarball": f"{GITHUB}/archive/refs/heads/{BRANCH}.tar.gz",
            "apiZipball": f"https://api.github.com/repos/{OWNER}/{REPO}/zipball/{BRANCH}",
            "apiTreeRecursive": f"https://api.github.com/repos/{OWNER}/{REPO}/git/trees/{BRANCH}?recursive=1",
            "rawTemplate": f"{RAW}/{{path}}",
            "blobTemplate": f"{GITHUB}/blob/{BRANCH}/{{path}}",
            "treeTemplate": f"{GITHUB}/tree/{BRANCH}/{{path}}",
        },
        "aiContext": {
            "llmsTxt": f"{RAW}/llms.txt",
            "llmsFull": f"{RAW}/llms-full.md",
            "repoMap": f"{RAW}/REPO-MAP.md",
            "agentsMd": f"{RAW}/AGENTS.md",
            "gitmcp": f"https://gitmcp.io/{OWNER}/{REPO}",
            "gitmcpPages": f"https://{OWNER.lower()}.gitmcp.io/{REPO}",
            "deepwiki": f"https://deepwiki.com/{OWNER}/{REPO}",
            "deepwikiMcp": "https://mcp.deepwiki.com/mcp",
            "context7": f"https://context7.com/{OWNER.lower()}/{REPO.lower()}",
        },
        "stats": {
            "fileCount": len(files),
            "totalBytes": sum(sizes.values()),
            "largeFileThresholdBytes": LARGE_BYTES,
            "filesByType": dict(sorted(by_lang.items(), key=lambda kv: (-kv[1], kv[0]))),
        },
        "note": "Paths are repo-relative. Files at or above largeFileThresholdBytes are flagged large=true; skip them unless you need raw benchmark data. This file excludes itself and REPO-MAP.md.",
        "files": [
            ({"path": f, "bytes": sizes[f], "large": True} if sizes[f] >= LARGE_BYTES
             else {"path": f, "bytes": sizes[f]})
            for f in files
        ],
    }
    json_text = json.dumps(index, indent=1, ensure_ascii=False)
    # One file per line keeps diffs reviewable and the file greppable.
    json_text = re.sub(r'\{\n\s+"path": ([^\n]+),\n\s+"bytes": (\d+)(?:,\n\s+"large": true)?\n\s+\}',
                       lambda m: '{"path": %s, "bytes": %s%s}' % (
                           m.group(1), m.group(2),
                           ', "large": true' if '"large"' in m.group(0) else ''),
                       json_text)

    return index, json_text


def fmt_size(n: int) -> str:
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n/1:.1f} {unit}".replace(".0 ", " ")
        n /= 1024
    return f"{n:.1f} GB"


def build_map(files: list[str], index: dict) -> str:
    sizes = {e["path"]: e["bytes"] for e in index["files"]}
    warnings = []

    dir_count: dict[str, int] = defaultdict(int)
    dir_bytes: dict[str, int] = defaultdict(int)
    for f in files:
        parts = f.split("/")[:-1]
        for depth in range(1, len(parts) + 1):
            d = "/".join(parts[:depth])
            dir_count[d] += 1
            dir_bytes[d] += sizes[f]

    for d in DESCRIPTIONS:
        if not (ROOT / d).exists() or (d not in dir_count and not (ROOT / d).is_dir()):
            warnings.append(d)
    for _, p in FIND:
        if not (ROOT / p).exists():
            warnings.append(p)
    if warnings:
        print("warning: REPO-MAP references paths that do not exist: " + ", ".join(warnings),
              file=sys.stderr)

    a = index["access"]
    L: list[str] = []
    L.append("# Foundgine repository map")
    L.append("")
    L.append(f"> Generated by `tools/generate-repo-index.py` — do not edit by hand. "
             f"Version {index['version']}, {index['stats']['fileCount']} files, "
             f"{fmt_size(index['stats']['totalBytes'])}. Full file list with sizes: "
             f"[`repo-index.json`](repo-index.json).")
    L.append("")
    L.append("Foundgine is a configurable semantic and execution boundary for application "
             "capabilities, implemented for .NET 10 (`src/csharp`) and Java 27 (`src/java`), "
             "with thin TypeScript, Python and WebAssembly client SDKs. See "
             "[`llms.txt`](llms.txt) for the positioning and [`AGENTS.md`](AGENTS.md) for "
             "working rules.")
    L.append("")
    L.append("## Get the whole repository")
    L.append("")
    L.append(f"- Clone: `git clone {a['clone']}`")
    L.append(f"- Zip: {a['zip']}")
    L.append(f"- Tarball: {a['tarball']}")
    L.append(f"- Any file, raw: `{a['rawTemplate']}`")
    L.append(f"- Any file, rendered: `{a['blobTemplate']}`")
    L.append(f"- Complete file list (GitHub API): {a['apiTreeRecursive']}")
    L.append("- Machine-readable index in this repo: [`repo-index.json`](repo-index.json)")
    L.append("- Access guide (MCP servers, indexes, crawlers): [`docs/AI-ACCESS.md`](docs/AI-ACCESS.md)")
    L.append("")
    L.append("## Where is…")
    L.append("")
    L.append("| Looking for | Path |")
    L.append("|---|---|")
    for label, p in FIND:
        L.append(f"| {label} | [`{p}`]({p}) |")
    L.append("")

    L.append("## Top-level layout")
    L.append("")
    L.append("| Path | Files | Size | What it is |")
    L.append("|---|---:|---:|---|")
    top_dirs = sorted({f.split("/")[0] for f in files if "/" in f})
    top_files = sorted(f for f in files if "/" not in f)
    for d in top_dirs:
        L.append(f"| [`{d}/`]({d}/) | {dir_count[d]} | {fmt_size(dir_bytes[d])} | {DESCRIPTIONS.get(d, '')} |")
    for f in top_files:
        L.append(f"| [`{f}`]({f}) | 1 | {fmt_size(sizes[f])} | |")
    L.append("")

    L.append("## Directory tree (to depth 4, with file counts)")
    L.append("")
    L.append("```text")
    dirs = sorted(d for d in dir_count if d.count("/") < 4)
    for d in dirs:
        depth = d.count("/")
        name = d.split("/")[-1]
        desc = f"  # {DESCRIPTIONS[d]}" if d in DESCRIPTIONS else ""
        L.append(f"{'  ' * depth}{name}/  ({dir_count[d]} files){desc}")
    L.append("```")
    L.append("")

    large = [(f, s) for f, s in sizes.items() if s >= LARGE_BYTES]
    if large:
        L.append(f"## Large files (≥ {fmt_size(LARGE_BYTES)}) — usually safe to skip")
        L.append("")
        L.append("Raw benchmark data. Summaries and conclusions are in the `docs-site/agent-benchmark/` "
                 "pages and in `docs/performance/`.")
        L.append("")
        L.append("| Path | Size |")
        L.append("|---|---:|")
        for f, s in sorted(large, key=lambda kv: -kv[1])[:40]:
            L.append(f"| `{f}` | {fmt_size(s)} |")
        if len(large) > 40:
            L.append(f"| … {len(large) - 40} more (see `repo-index.json`, `large: true`) | |")
        L.append("")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if generated files are stale")
    args = ap.parse_args()

    files = list_files()
    index, json_text = build(files)
    map_text = build_map(files, index)
    targets = {ROOT / "repo-index.json": json_text + "\n", ROOT / "REPO-MAP.md": map_text}

    stale = [p.name for p, t in targets.items()
             if not p.exists() or p.read_text(encoding="utf-8") != t]
    if args.check:
        if stale:
            print("stale: " + ", ".join(stale) + " — run: python tools/generate-repo-index.py",
                  file=sys.stderr)
            return 1
        print("repo index is up to date")
        return 0

    for p, t in targets.items():
        p.write_text(t, encoding="utf-8", newline="\n")
    print(f"wrote repo-index.json and REPO-MAP.md ({len(files)} files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
