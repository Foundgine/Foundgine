"""Generate machine-readable and LLM-readable indexes of the whole repository.

Outputs (written to the repository root):

  repo-index.json  Every tracked file (path + size in bytes) plus clone / zip / raw URL
                   templates. Lets an AI agent or crawler enumerate the repo without
                   cloning it or paging through the GitHub tree UI.
  REPO-MAP.md      Directory map with file counts, sizes and one-line descriptions, plus
                   a "where is X" index. Written for LLMs and humans.

Usage (from anywhere):

  python tools/generate-repo-index.py            # rewrite both files
  python tools/generate-repo-index.py --check    # exit 1 if either file is out of date

The file list is `git ls-files` (tracked) plus untracked files that are not ignored, so
build output (target/, bin/, obj/ ...) never appears. If the directory is not a git
checkout (for example an unpacked zip) the same .gitignore rules are applied through a
temporary empty git directory. Output is deterministic: no timestamps.

Standard library only; Python 3.8+.
"""
